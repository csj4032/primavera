GRANT ALL PRIVILEGES ON primavera.* TO 'primavera'@'%' IDENTIFIED BY '${PRIMAVERA_ADMIN_PASSWORD}';
GRANT ALL PRIVILEGES ON primavera_production.* TO 'primavera'@'%';
GRANT ALL PRIVILEGES ON primavera_microservices.* TO 'primavera'@'%';
