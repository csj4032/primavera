FLUSH PRIVILEGES;

-- ==============================================
-- 1. 운영용 애플리케이션 데이터베이스 (primavera_production)
-- ==============================================

USE primavera_production;

-- 사용자 및 권한 관리
CREATE TABLE IF NOT EXISTS USERS
(
    ID         BIGINT AUTO_INCREMENT PRIMARY KEY,
    EMAIL      VARCHAR(100) UNIQUE NOT NULL,
    PASSWORD   VARCHAR(255)        NOT NULL,
    NICKNAME   VARCHAR(50)         NOT NULL,
    STATUS     VARCHAR(20) DEFAULT 'ACTIVE',
    CREATED_AT DATETIME    DEFAULT CURRENT_TIMESTAMP,
    UPDATED_AT DATETIME    DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    CREATED_BY BIGINT,
    UPDATED_BY BIGINT,
    LAST_LOGIN DATETIME,
    LOGIN_COUNT BIGINT DEFAULT 0,
    VERSION    BIGINT DEFAULT 0, -- 낙관적 락킹
    INDEX IDX_EMAIL (EMAIL),
    INDEX IDX_STATUS (STATUS),
    INDEX IDX_CREATED_AT (CREATED_AT),
    INDEX IDX_LAST_LOGIN (LAST_LOGIN)
) ENGINE = InnoDB
  DEFAULT CHARSET = utf8mb4
  COLLATE = utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS ROLES
(
    ID          BIGINT AUTO_INCREMENT PRIMARY KEY,
    NAME        VARCHAR(50) UNIQUE NOT NULL,
    DESCRIPTION VARCHAR(255),
    TYPE        INT                NOT NULL,
    IS_ACTIVE   BOOLEAN    DEFAULT TRUE,
    CREATED_AT  DATETIME   DEFAULT CURRENT_TIMESTAMP,
    UPDATED_AT  DATETIME   DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    VERSION     BIGINT     DEFAULT 0,
    INDEX IDX_TYPE (TYPE),
    INDEX IDX_IS_ACTIVE (IS_ACTIVE)
) ENGINE = InnoDB
  DEFAULT CHARSET = utf8mb4
  COLLATE = utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS USER_ROLES
(
    ID         BIGINT AUTO_INCREMENT PRIMARY KEY,
    USER_ID    BIGINT   NOT NULL,
    ROLE_ID    BIGINT   NOT NULL,
    GRANTED_AT DATETIME DEFAULT CURRENT_TIMESTAMP,
    GRANTED_BY BIGINT,
    EXPIRES_AT DATETIME,
    IS_ACTIVE  BOOLEAN  DEFAULT TRUE,
    FOREIGN KEY (USER_ID) REFERENCES USERS (ID) ON DELETE CASCADE,
    FOREIGN KEY (ROLE_ID) REFERENCES ROLES (ID) ON DELETE CASCADE,
    FOREIGN KEY (GRANTED_BY) REFERENCES USERS (ID) ON DELETE SET NULL,
    UNIQUE KEY UNIQUE_USER_ROLE (USER_ID, ROLE_ID),
    INDEX IDX_GRANTED_AT (GRANTED_AT),
    INDEX IDX_EXPIRES_AT (EXPIRES_AT),
    INDEX IDX_IS_ACTIVE (IS_ACTIVE)
) ENGINE = InnoDB
  DEFAULT CHARSET = utf8mb4
  COLLATE = utf8mb4_unicode_ci;

-- 소셜 로그인 연결 정보 (보안 강화)
CREATE TABLE IF NOT EXISTS USER_CONNECTIONS
(
    ID               BIGINT AUTO_INCREMENT PRIMARY KEY,
    USER_ID          BIGINT       NOT NULL,
    PROVIDER_ID      VARCHAR(50)  NOT NULL,
    PROVIDER_USER_ID VARCHAR(100) NOT NULL,
    DISPLAY_NAME     VARCHAR(100),
    PROFILE_URL      VARCHAR(500),
    IMAGE_URL        VARCHAR(500),
    ACCESS_TOKEN     TEXT, -- 암호화 필요
    REFRESH_TOKEN    TEXT, -- 암호화 필요
    EXPIRE_TIME      BIGINT,
    IS_ACTIVE        BOOLEAN  DEFAULT TRUE,
    CREATED_AT       DATETIME DEFAULT CURRENT_TIMESTAMP,
    UPDATED_AT       DATETIME DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    LAST_USED_AT     DATETIME,
    FOREIGN KEY (USER_ID) REFERENCES USERS (ID) ON DELETE CASCADE,
    UNIQUE KEY UNIQUE_PROVIDER_USER (PROVIDER_ID, PROVIDER_USER_ID),
    INDEX IDX_IS_ACTIVE (IS_ACTIVE),
    INDEX IDX_LAST_USED_AT (LAST_USED_AT)
) ENGINE = InnoDB
  DEFAULT CHARSET = utf8mb4
  COLLATE = utf8mb4_unicode_ci;

-- 운영용 게시글 테이블
CREATE TABLE IF NOT EXISTS POSTS
(
    ID            BIGINT AUTO_INCREMENT PRIMARY KEY,
    AUTHOR_ID     BIGINT       NOT NULL,
    TITLE         VARCHAR(255) NOT NULL,
    CONTENT       LONGTEXT     NOT NULL,
    SUMMARY       TEXT,
    VIEW_COUNT    BIGINT      DEFAULT 0,
    LIKE_COUNT    BIGINT      DEFAULT 0,
    COMMENT_COUNT BIGINT      DEFAULT 0,
    STATUS        VARCHAR(20) DEFAULT 'DRAFT',
    PUBLISHED_AT  DATETIME,
    CREATED_AT    DATETIME    DEFAULT CURRENT_TIMESTAMP,
    UPDATED_AT    DATETIME    DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    VERSION       BIGINT      DEFAULT 0,
    FOREIGN KEY (AUTHOR_ID) REFERENCES USERS (ID) ON DELETE CASCADE,
    INDEX IDX_AUTHOR_ID (AUTHOR_ID),
    INDEX IDX_STATUS (STATUS),
    INDEX IDX_PUBLISHED_AT (PUBLISHED_AT),
    INDEX IDX_VIEW_COUNT (VIEW_COUNT),
    FULLTEXT IDX_TITLE_CONTENT (TITLE, CONTENT)
) ENGINE = InnoDB
  DEFAULT CHARSET = utf8mb4
  COLLATE = utf8mb4_unicode_ci;

-- 운영용 댓글 테이블
CREATE TABLE IF NOT EXISTS COMMENTS
(
    ID         BIGINT AUTO_INCREMENT PRIMARY KEY,
    POST_ID    BIGINT   NOT NULL,
    PARENT_ID  BIGINT,
    AUTHOR_ID  BIGINT   NOT NULL,
    CONTENT    LONGTEXT NOT NULL,
    STATUS     VARCHAR(20) DEFAULT 'ACTIVE',
    LIKE_COUNT BIGINT      DEFAULT 0,
    DEPTH      INT         DEFAULT 0,
    SORT_ORDER BIGINT      DEFAULT 0,
    CREATED_AT DATETIME    DEFAULT CURRENT_TIMESTAMP,
    UPDATED_AT DATETIME    DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    VERSION    BIGINT      DEFAULT 0,
    FOREIGN KEY (POST_ID) REFERENCES POSTS (ID) ON DELETE CASCADE,
    FOREIGN KEY (PARENT_ID) REFERENCES COMMENTS (ID) ON DELETE CASCADE,
    FOREIGN KEY (AUTHOR_ID) REFERENCES USERS (ID) ON DELETE CASCADE,
    INDEX IDX_POST_ID (POST_ID),
    INDEX IDX_PARENT_ID (PARENT_ID),
    INDEX IDX_STATUS (STATUS),
    INDEX IDX_DEPTH_SORT (DEPTH, SORT_ORDER)
) ENGINE = InnoDB
  DEFAULT CHARSET = utf8mb4
  COLLATE = utf8mb4_unicode_ci;

-- 파일 관리 테이블 (운영 최적화)
CREATE TABLE IF NOT EXISTS FILE_UPLOADS
(
    ID                BIGINT AUTO_INCREMENT PRIMARY KEY,
    POST_ID           BIGINT,
    ORIGINAL_FILENAME VARCHAR(255) NOT NULL,
    STORED_FILENAME   VARCHAR(255) NOT NULL,
    FILE_PATH         VARCHAR(500) NOT NULL,
    FILE_SIZE         BIGINT       NOT NULL,
    CONTENT_TYPE      VARCHAR(100),
    FILE_TYPE         VARCHAR(50),
    UPLOAD_STATUS     VARCHAR(20) DEFAULT 'UPLOADED',
    VIRUS_SCAN_STATUS VARCHAR(20) DEFAULT 'PENDING',
    VIRUS_SCAN_RESULT VARCHAR(100),
    PROCESSED_AT      DATETIME,
    UPLOADED_BY       BIGINT,
    ACCESS_COUNT      BIGINT      DEFAULT 0,
    LAST_ACCESS_AT    DATETIME,
    RETENTION_UNTIL   DATETIME, -- 데이터 보존 기간
    CREATED_AT        DATETIME    DEFAULT CURRENT_TIMESTAMP,
    UPDATED_AT        DATETIME    DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    FOREIGN KEY (POST_ID) REFERENCES POSTS (ID) ON DELETE SET NULL,
    FOREIGN KEY (UPLOADED_BY) REFERENCES USERS (ID) ON DELETE SET NULL,
    INDEX IDX_POST_ID (POST_ID),
    INDEX IDX_FILE_TYPE (FILE_TYPE),
    INDEX IDX_UPLOAD_STATUS (UPLOAD_STATUS),
    INDEX IDX_VIRUS_SCAN_STATUS (VIRUS_SCAN_STATUS),
    INDEX IDX_UPLOADED_BY (UPLOADED_BY),
    INDEX IDX_RETENTION_UNTIL (RETENTION_UNTIL)
) ENGINE = InnoDB
  DEFAULT CHARSET = utf8mb4
  COLLATE = utf8mb4_unicode_ci;

-- 사용자 세션 관리 (보안)
CREATE TABLE IF NOT EXISTS USER_SESSIONS
(
    ID            VARCHAR(128) PRIMARY KEY,
    USER_ID       BIGINT       NOT NULL,
    IP_ADDRESS    VARCHAR(45)  NOT NULL,
    USER_AGENT    TEXT,
    CREATED_AT    DATETIME DEFAULT CURRENT_TIMESTAMP,
    LAST_ACCESS   DATETIME DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    EXPIRES_AT    DATETIME     NOT NULL,
    IS_ACTIVE     BOOLEAN  DEFAULT TRUE,
    SESSION_DATA  JSON,
    FOREIGN KEY (USER_ID) REFERENCES USERS (ID) ON DELETE CASCADE,
    INDEX IDX_USER_ID (USER_ID),
    INDEX IDX_EXPIRES_AT (EXPIRES_AT),
    INDEX IDX_IS_ACTIVE (IS_ACTIVE),
    INDEX IDX_IP_ADDRESS (IP_ADDRESS)
) ENGINE = InnoDB
  DEFAULT CHARSET = utf8mb4
  COLLATE = utf8mb4_unicode_ci;

-- 감사 로그 테이블
CREATE TABLE IF NOT EXISTS AUDIT_LOGS
(
    ID              BIGINT AUTO_INCREMENT PRIMARY KEY,
    TABLE_NAME      VARCHAR(64)  NOT NULL,
    RECORD_ID       BIGINT       NOT NULL,
    ACTION          VARCHAR(20)  NOT NULL, -- INSERT, UPDATE, DELETE
    OLD_VALUES      JSON,
    NEW_VALUES      JSON,
    CHANGED_BY      BIGINT,
    CHANGE_REASON   VARCHAR(255),
    IP_ADDRESS      VARCHAR(45),
    USER_AGENT      TEXT,
    CREATED_AT      DATETIME DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (CHANGED_BY) REFERENCES USERS (ID) ON DELETE SET NULL,
    INDEX IDX_TABLE_RECORD (TABLE_NAME, RECORD_ID),
    INDEX IDX_ACTION (ACTION),
    INDEX IDX_CHANGED_BY (CHANGED_BY),
    INDEX IDX_CREATED_AT (CREATED_AT)
) ENGINE = InnoDB
  DEFAULT CHARSET = utf8mb4
  COLLATE = utf8mb4_unicode_ci;

